let locale: Locale = "en";
const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return locale;
}

export function setLocale(value: string): Locale {
  locale = value === "zh-CN" ? "zh-CN" : "en";
  listeners.forEach((listener) => listener());
  return locale;
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  const table = locale === "zh-CN" ? ZH : EN;
  const template = table[key] ?? EN[key];
  if (!template) return key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (
    params[name] === undefined || params[name] === null ? match : String(params[name])
  ));
}

export function present(code: string | undefined, params: Record<string, string> | undefined, fallback: string): string {
  if (!code || (EN[code] === undefined && ZH[code] === undefined)) return fallback;
  return t(code, params ?? {});
}

export function useT(): typeof t {
  useSyncExternalStore(subscribe, getLocale, getLocale);
  return t;
}
