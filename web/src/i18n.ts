let locale: Locale = "en";
const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return locale;
}

export function setLocale(value: string): Locale {
  locale = value === "zh-CN" ? "zh-CN" : "en";
  // Lets the browser choose Chinese glyph forms and line breaking.
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  listeners.forEach((listener) => listener());
  return locale;
}

/** The browser's preferred interface language, for people who never chose one. */
export function browserLocale(languages: readonly string[] = typeof navigator === "undefined" ? [] : (navigator.languages?.length ? navigator.languages : [navigator.language])): Locale {
  for (const language of languages) {
    const tag = (language || "").toLowerCase();
    if (tag.startsWith("zh")) return "zh-CN";
    if (tag.startsWith("en")) return "en";
  }
  return "en";
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  const table = locale === "zh-CN" ? ZH : EN;
  const template = table[key] ?? EN[key];
  if (!template) return key;
  const translated = template.replace(/\{(\w+)\}/g, (match, name: string) => (
    params[name] === undefined || params[name] === null ? match : String(params[name])
  ));
  return /Mac/i.test(navigator.platform) ? translated : translated.replace(/⌘(?=[A-Z.])/g, "Ctrl+").replace(/⌥(?=[A-Z.])/g, "Alt+");
}

export function present(code: string | undefined, params: Record<string, string> | undefined, fallback: string): string {
  if (!code || (EN[code] === undefined && ZH[code] === undefined)) return fallback;
  return t(code, params ?? {});
}

export function useT(): typeof t {
  useSyncExternalStore(subscribe, getLocale, getLocale);
  return t;
}
